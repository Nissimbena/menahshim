"""
Builds the "מנאחסים" logo assets from the Tel Aviv Modernist Bold outlines.

The wordmark is shaped with HarfBuzz (real RTL order + the font's own
kerning), converted to plain SVG paths (no font dependency), and the ס is
replaced by a basketball: a red circle the height of the letters, sitting on
the baseline, with seams knocked out at the width of the letters' counters.

Outputs:
  src/brand/logoPaths.ts          path data consumed by src/brand/Logo.ts
  public/brand/logo-horizontal.svg
  public/brand/logo-horizontal-mono.svg
  public/brand/logo-mark.svg
  public/favicon.svg
  public/brand/icon-maskable.svg  (source for the PWA PNGs)

Dev-only. Requires: pip install fonttools uharfbuzz
Run from the repo root:  python3 scripts/build-logo.py
"""
import json, math, os
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "public/fonts/TelAvivModernist-Bold.otf")
WORD = "מנאחסים"
BALL_CHAR = "ס"
TRACKING = -24        # tighter than default, in font units (1000/em)
LETTER_H = 560        # Hebrew letter height (= the font's x-height)
OVERSHOOT = 10        # round shapes overshoot the flat ones, like the font's own ס
SEAM = 90              # seam width: half the 180-unit stem. A full-stem seam
                       # slices the ball into three bars and kills the read at 24px.

TEXT = "#F5F1EA"
RED = "#DD1B22"
BG = "#0C0B0B"

font_tt = TTFont(FONT)
glyphset = font_tt.getGlyphSet()
cmap = font_tt.getBestCmap()
ball_gid_name = cmap[ord(BALL_CHAR)]

blob = hb.Blob.from_file_path(FONT)
hb_font = hb.Font(hb.Face(blob))
buf = hb.Buffer()
buf.add_str(WORD)
buf.guess_segment_properties()
hb.shape(hb_font, buf, {"kern": True})

# Visual (left-to-right) layout. Flip y: font units are y-up, SVG is y-down.
x = 0.0
letters = []
ink = []
ball = None
glyphs = list(zip(buf.glyph_infos, buf.glyph_positions))
for i, (info, pos) in enumerate(glyphs):
    name = hb_font.glyph_to_string(info.codepoint)
    adv = pos.x_advance + (TRACKING if i < len(glyphs) - 1 else 0)
    if name == ball_gid_name:
        d = LETTER_H + 2 * OVERSHOOT
        ball = {"cx": x + adv / 2, "cy": -(LETTER_H / 2), "r": d / 2}
    else:
        pen = SVGPathPen(glyphset, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
        tpen = TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, 0))
        glyphset[name].draw(tpen)
        letters.append(pen.getCommands())
        bp = BoundsPen(glyphset)
        glyphset[name].draw(bp)
        if bp.bounds:
            ink.append((x + pos.x_offset + bp.bounds[0], x + pos.x_offset + bp.bounds[2]))
    x += adv

width = x
top = -(LETTER_H + OVERSHOOT)
height = LETTER_H + 2 * OVERSHOOT


def seams(cx, cy, r, w):
    """Three seams: the horizontal equator and two side arcs."""
    # Side arcs: circles centred outside the ball, crossing it top-to-bottom.
    k = 1.25 * r          # arc radius
    off = r * 1.62        # distance of the arc centre from the ball centre
    paths = [f"M{cx - r:.1f} {cy:.1f}H{cx + r:.1f}"]
    for s in (-1, 1):
        acx = cx + s * off
        # intersection of arc circle and ball circle -> endpoints
        dx = (off * off + r * r - k * k) / (2 * off)
        dy = math.sqrt(max(r * r - dx * dx, 0))
        x1 = cx + s * dx
        paths.append(
            f"M{x1:.1f} {cy - dy:.1f}A{k:.1f} {k:.1f} 0 0 {0 if s > 0 else 1} {x1:.1f} {cy + dy:.1f}"
        )
    return paths, w


seam_paths, seam_w = seams(ball["cx"], ball["cy"], ball["r"], SEAM)
pad = 0
left = min(a for a, _ in ink)
right = max(b for _, b in ink)
view = [round(left - pad, 1), round(top - pad, 1), round(right - left + 2 * pad, 1), round(height + 2 * pad, 1)]

data = {
    "viewBox": " ".join(str(v) for v in view),
    "width": view[2],
    "height": view[3],
    "letters": " ".join(letters),
    "ball": {k: round(v, 1) for k, v in ball.items()},
    "seams": seam_paths,
    "seamWidth": seam_w,
}

# ---------- TS module ----------
os.makedirs(os.path.join(ROOT, "src/brand"), exist_ok=True)
with open(os.path.join(ROOT, "src/brand/logoPaths.ts"), "w") as fh:
    fh.write("// Generated by scripts/build-logo.py - do not edit by hand.\n")
    fh.write("export const LOGO = " + json.dumps(data, ensure_ascii=False, indent=2) + " as const;\n")

# ---------- static SVGs ----------
b = data["ball"]


def ball_group(mask_id, fill, seam_mode="knockout", seam_color=BG):
    seams_d = "".join(f'<path d="{p}"/>' for p in seam_paths)
    if seam_mode == "knockout":
        return (
            f'<mask id="{mask_id}">'
            f'<circle cx="{b["cx"]}" cy="{b["cy"]}" r="{b["r"]}" fill="#fff"/>'
            f'<g fill="none" stroke="#000" stroke-width="{seam_w}" stroke-linecap="butt">{seams_d}</g></mask>'
            f'<circle cx="{b["cx"]}" cy="{b["cy"]}" r="{b["r"]}" fill="{fill}" mask="url(#{mask_id})"/>'
        )
    return (
        f'<circle cx="{b["cx"]}" cy="{b["cy"]}" r="{b["r"]}" fill="{fill}"/>'
        f'<g fill="none" stroke="{seam_color}" stroke-width="{seam_w}">{seams_d}</g>'
    )


def svg(view_box, body, w=None, h=None, title="מנאחסים"):
    size = f' width="{w}" height="{h}"' if w else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}"{size} role="img">'
        f"<title>{title}</title>{body}</svg>\n"
    )


os.makedirs(os.path.join(ROOT, "public/brand"), exist_ok=True)
vb = data["viewBox"]
with open(os.path.join(ROOT, "public/brand/logo-horizontal.svg"), "w") as fh:
    fh.write(svg(vb, f'<path fill="{TEXT}" d="{data["letters"]}"/>' + ball_group("m", RED)))
with open(os.path.join(ROOT, "public/brand/logo-horizontal-mono.svg"), "w") as fh:
    fh.write(svg(vb, f'<path fill="#FFFFFF" d="{data["letters"]}"/>' + ball_group("m", "#FFFFFF")))

# Mark: the ball on its own, re-centred at the origin.
r = b["r"]


def mark_body(cx, cy, rr, mask_id="b", fill=RED):
    s = rr / r
    paths = "".join(
        f'<path d="{p}"/>' for p in seams(cx, cy, rr, SEAM * s)[0]
    )
    return (
        f'<mask id="{mask_id}">'
        f'<circle cx="{cx}" cy="{cy}" r="{rr}" fill="#fff"/>'
        f'<g fill="none" stroke="#000" stroke-width="{SEAM * s:.1f}">{paths}</g></mask>'
        f'<circle cx="{cx}" cy="{cy}" r="{rr}" fill="{fill}" mask="url(#{mask_id})"/>'
    )


with open(os.path.join(ROOT, "public/brand/logo-mark.svg"), "w") as fh:
    fh.write(svg("0 0 100 100", mark_body(50, 50, 50)))
# Favicon: same ball, with the seams opened up a touch so they survive at 16px.
with open(os.path.join(ROOT, "public/favicon.svg"), "w") as fh:
    s = 48 / r
    paths = "".join(f'<path d="{p}"/>' for p in seams(50, 50, 48, 0)[0])
    fh.write(svg("0 0 100 100",
        '<mask id="f"><circle cx="50" cy="50" r="48" fill="#fff"/>'
        f'<g fill="none" stroke="#000" stroke-width="13">{paths}</g></mask>'
        f'<circle cx="50" cy="50" r="48" fill="{RED}" mask="url(#f)"/>'))
# Maskable app icon: full-bleed warm-black square, ball inside the 80% safe zone.
with open(os.path.join(ROOT, "public/brand/icon-maskable.svg"), "w") as fh:
    fh.write(svg("0 0 512 512", f'<rect width="512" height="512" fill="{BG}"/>' + mark_body(256, 256, 150)))
# Regular ("any") app icon: rounded square.
with open(os.path.join(ROOT, "public/brand/icon-any.svg"), "w") as fh:
    fh.write(svg("0 0 512 512", f'<rect width="512" height="512" rx="112" fill="{BG}"/>' + mark_body(256, 256, 176)))

print("viewBox", vb, "ball", b)
